import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
import { emptyPlanDraft } from "../lib/store/plan-draft";

test("populated restore to field comparison and printable report", async ({ page }) => {
  const weather = JSON.parse(readFileSync("data/predownload/weather/power_20.0_95.000.json", "utf8")).weather;
  const stamp = new Date().toISOString();
  const field = { id: "e2e-field", name: "Restored Magway field", geometry: { type: "Point", coordinates: [94.95, 20.15] }, centroid: [94.95, 20.15], samplePoints: [[94.95,20.15]], areaHa: null, region: "magway", locationConfirmed: true, irrigation: "none", createdAt: stamp, updatedAt: stamp };
  const draft = emptyPlanDraft();
  draft.place = { id: "typed:magway:test", name: "Magway", context: "Magway", region: "magway", source: "typed" };
  draft.mainCropId = "sesame";
  draft.refinements.sequence = { ...draft.refinements.sequence, sowing: { kind: "exact", date: "2026-05-15" }, harvest: { kind: "exact", date: "2026-08-15" }, state: "confirmed" };
  draft.refinements.water = { value: "rain-only", state: "saved" };
  draft.refinements.goal = { value: "water", state: "saved" };
  await page.route("**/api/field/*/conditions?*", route => route.fulfill({ json: { fieldId: field.id, fetchedAt: stamp, climateAvailable: true, soilAvailable: false, weather, sources: [{ dataset: "NASA POWER cached fixture" }], power: { status: "ok", version: weather.meta.apiVersion, fillValue: -999, timeStandard: "UTC", sources: weather.meta.sources, retrievedAt: stamp, start: weather.dates[0], end: weather.dates.at(-1), elevationM: weather.elevationM, units: weather.meta.units } } }));
  await page.route("**/api/field/*/remote-sensing", route => route.fulfill({ json: { fieldId: field.id, checkedAt: stamp, smap: { status: "unconfigured" }, hls: { status: "unavailable" }, srtm: { status: "unconfigured" } } }));
  await page.goto("/welcome");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.goto("/settings");
  await page.getByLabel("Choose a backup file").setInputFiles({ name: "populated.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify({ app: "nasa-farming-app", version: 3, exportedAt: stamp, fields: [field], rotations: [], planDraft: draft })) });
  await expect(page.getByRole("status")).toContainText("Restored 1 fields");
  await page.goto("/plan");
  await page.getByRole("combobox", { name: "Confirmed field in this region" }).click();
  await page.getByRole("option", { name: field.name }).click();
  await page.getByRole("button", { name: "Save sequence and compare this field" }).click();
  await page.getByRole("link", { name: "Open field-informed comparison" }).click();
  await expect(page.getByRole("heading", { name: "Compare crop plans" })).toBeVisible();
  await expect(page.getByText(/complete past years from 2016–2025/).first()).toBeVisible();
  await expect(page.getByText("How we checked these choices")).toBeVisible();
  await expect(page.getByRole("heading", { name: "Your choices" })).toBeVisible();
  await expect(page.getByRole("link", { name: "See my farmer summary" })).toBeVisible();
  await expect(page.getByText(/Evidence state:/)).toHaveCount(0);
  await page.screenshot({ path: test.info().outputPath("compare-view.png"), fullPage: true });
  await page.goto(`/fields/${field.id}/report`);
  await expect(page.getByRole("button", { name: "Print or save as PDF" })).toBeVisible();
  await page.emulateMedia({ media: "print" });
  const pdf = await page.pdf({ format: "A4" });
  expect(pdf.length).toBeGreaterThan(1000);
  await page.screenshot({ path: test.info().outputPath("print-view.png"), fullPage: true });
});

test("new farmer can preview, edit water, resume and export a local backup", async ({ page }) => {
  await page.goto("/welcome");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.goto("/plan");
  await page.getByLabel("Village or township").fill("Bogale");
  await page.getByRole("button", { name: /Ayeyarwady Rice/ }).click();
  await page.getByRole("button", { name: "Use this typed place" }).click();
  await page.getByRole("button", { name: "Rice ဆန်", exact: true }).click();
  await expect(page.getByText("Regional preview", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Water: Not set" }).click();
  await page.getByLabel("Rain only", { exact: true }).check();
  await page.getByRole("button", { name: "Save details" }).click();
  await page.reload();
  await expect(page.getByRole("button", { name: "Water: saved" })).toBeVisible();
  await page.goto("/settings");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export backup (JSON)" }).click();
  expect((await download).suggestedFilename()).toMatch(/\.json$/);
});
