import { ACCEPTANCE, SEASONS, type Grade, type StationReport } from "./weather";

const f = (x: number | null, d = 2) => (x === null ? "–" : x.toFixed(d));
const pct = (x: number | null) => (x === null ? "–" : `${Math.round(x * 100)}%`);
const GRADE_LABEL: Record<Grade, string> = {
  good: "Good",
  "usable-with-care": "Usable with care",
  poor: "Poor",
  "insufficient-data": "Not enough data",
};

export interface WeatherValidationRun {
  generatedAt: string;
  product: string;
  powerTimeStandard: string;
  groundTruth: string;
  stations: StationReport[];
}

/** Markdown report from a run. Kept deterministic so the committed file only changes when results do. */
export function renderWeatherReport(run: WeatherValidationRun): string {
  const L: string[] = [];
  L.push("# Weather Validation: NASA POWER vs Myanmar stations");
  L.push("");
  L.push("> Generated by `npm run validate:weather` — do not edit by hand. Results JSON: `data/validation/power-vs-ghcn.json`.");
  L.push("");
  L.push(`- **Product checked:** ${run.product} (daily, ${run.powerTimeStandard} days, as the app requests it)`);
  L.push(`- **Ground truth:** ${run.groundTruth}`);
  L.push(`- **Generated:** ${run.generatedAt.slice(0, 10)}`);
  L.push("");
  L.push("## Summary grades");
  L.push("");
  L.push("| Station | Period | Max temp | Min temp | Monthly rain | Heat days >35 °C | Cold nights <15 °C |");
  L.push("|:--|:--|:--|:--|:--|:--|:--|");
  for (const s of run.stations) {
    const h35 = s.tmax.thresholds.find((t) => t.thresholdC === 35);
    const c15 = s.tmin.thresholds.find((t) => t.thresholdC === 15);
    L.push(
      `| ${s.station.name} | ${s.period.start.slice(0, 4)}–${s.period.end.slice(0, 4)} | ${GRADE_LABEL[s.tmax.daily.grade]} | ${GRADE_LABEL[s.tmin.daily.grade]} | ${GRADE_LABEL[s.rain.monthly.grade]} | ${h35 ? GRADE_LABEL[h35.grade] : "–"} | ${c15 ? GRADE_LABEL[c15.grade] : "–"} |`,
    );
  }
  L.push("");
  L.push("## Acceptance rules");
  L.push("");
  const a = ACCEPTANCE;
  L.push(`- **Daily temperature:** good if |bias| ≤ ${a.temperature.good.bias} °C and RMSE ≤ ${a.temperature.good.rmse} °C; usable if ≤ ${a.temperature.usable.bias} °C and ≤ ${a.temperature.usable.rmse} °C.`);
  L.push(`- **Monthly rain totals:** good if |relative bias| ≤ ${pct(a.monthlyRain.good.relBias)} and r ≥ ${a.monthlyRain.good.r}; usable if ≤ ${pct(a.monthlyRain.usable.relBias)} and r ≥ ${a.monthlyRain.usable.r}. A month counts only with station readings on ≥ ${pct(a.monthCompleteness)} of its days.`);
  L.push(`- **Limit days (heat, cold):** good if POWER catches ≥ ${pct(a.thresholdDays.good.pod)} of observed days with ≤ ${pct(a.thresholdDays.good.far)} false alarms; usable at ≥ ${pct(a.thresholdDays.usable.pod)} and ≤ ${pct(a.thresholdDays.usable.far)}. Needs ≥ ${a.thresholdDays.minEvents} observed days.`);
  L.push("- These are this project's rules for screening-level use, chosen before the results were seen. They are not an international standard.");
  L.push("");

  for (const s of run.stations) {
    L.push(`## ${s.station.name} (${s.station.id})`);
    L.push("");
    L.push(`Station ${s.station.lat}, ${s.station.lon}, ${s.station.elevationM} m. POWER cell centre ${f(s.powerCell.lat, 3)}, ${f(s.powerCell.lon, 3)}, ${s.powerCell.elevationM ?? "–"} m (difference ${s.elevationDiffM ?? "–"} m). Values dropped for NCEI quality flags: rain ${s.qcRejected.prcp}, max temp ${s.qcRejected.tmax}, min temp ${s.qcRejected.tmin}.`);
    L.push("");
    L.push("| Variable | Days | Station mean | POWER mean | Bias | RMSE | r | Grade |");
    L.push("|:--|--:|--:|--:|--:|--:|--:|:--|");
    for (const t of [s.tmax, s.tmin]) {
      const d = t.daily;
      L.push(`| ${t.variable === "tmax" ? "Max temp °C" : "Min temp °C"} | ${d.n} | ${f(d.meanObs, 1)} | ${f(d.meanModel, 1)} | ${f(d.bias)} | ${f(d.rmse)} | ${f(d.r)} | ${GRADE_LABEL[d.grade]} |`);
    }
    const r = s.rain;
    if (r.wetDaysOnly) {
      L.push(`| Rain mm/day | ${r.daily.n} | – | – | – | – | – | Not comparable: station logs mostly wet days |`);
    } else {
      L.push(`| Rain mm/day | ${r.daily.n} | ${f(r.daily.meanObs)} | ${f(r.daily.meanModel)} | ${f(r.daily.bias)} | ${f(r.daily.rmse)} | ${f(r.daily.r)} | (daily: info only) |`);
    }
    L.push(`| Rain mm/month | ${r.monthly.n} | ${f(r.monthly.meanObs, 0)} | ${f(r.monthly.meanModel, 0)} | ${f(r.monthly.bias, 0)} (${pct(r.monthly.relBias)}) | ${f(r.monthly.rmse, 0)} | ${f(r.monthly.r)} | ${GRADE_LABEL[r.monthly.grade]} |`);
    L.push("");
    L.push("**By season** (temperature bias °C / monthly rain relative bias):");
    L.push("");
    L.push("| Season | Max temp bias | Min temp bias | Rain bias | Rain months |");
    L.push("|:--|--:|--:|--:|--:|");
    for (const se of SEASONS) {
      L.push(`| ${se} | ${f(s.tmax.bySeason[se].bias)} | ${f(s.tmin.bySeason[se].bias)} | ${pct(r.monthlyBySeason[se].relBias)} | ${r.monthlyBySeason[se].n} |`);
    }
    L.push("");
    L.push("**Limit days** (the thresholds the crop catalog uses):");
    L.push("");
    L.push("| Limit | Observed days | Caught | False alarms | Grade |");
    L.push("|:--|--:|--:|--:|:--|");
    for (const t of [...s.tmax.thresholds, ...s.tmin.thresholds]) {
      L.push(`| ${t.kind === "heat" ? "Max >" : "Min <"} ${t.thresholdC} °C | ${t.observedEvents} | ${pct(t.pod)} | ${pct(t.far)} | ${GRADE_LABEL[t.grade]} |`);
    }
    L.push("");
    const shift = `${r.bestLag >= 0 ? "+" : ""}${r.bestLag}`;
    if (r.wetDaysOnly) {
      L.push(`**Wet days:** the station has a rain reading on only ${pct(r.rainCoverage)} of its reporting days and leaves most dry days blank, so false alarms and daily bias cannot be measured here. Of the days it did report, POWER (shifted ${shift} day) also shows ≥ ${ACCEPTANCE.wetDayMm} mm on ${pct(r.wetDays.pod)} of the wet ones.`);
    } else {
      L.push(`**Wet days** (≥ ${ACCEPTANCE.wetDayMm} mm, compared at day shift ${shift}): caught ${pct(r.wetDays.pod)}, false alarms ${pct(r.wetDays.far)}, frequency bias ${f(r.wetDays.freqBias)}. Rain reading on ${pct(r.rainCoverage)} of station days.`);
    }
    L.push(`Daily rain r at shift −1/0/+1: ${f(r.lagR["-1"])} / ${f(r.lagR["0"])} / ${f(r.lagR["1"])}.`);
    L.push("");
  }
  return L.join("\n");
}
